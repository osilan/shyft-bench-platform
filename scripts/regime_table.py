#!/usr/bin/env python3
"""Generate ShyftBench/Generated/Regime.lean from data/regime/mon_Q_regime.csv.

The CSV is the frozen output of data/regime/calc_hydrological_regime.r
(Olga's decision, 2026-10-01: use it as is, do not re-classify).

    python3 scripts/regime_table.py          # write the Lean module
    python3 scripts/regime_table.py --check  # fail if the module is stale
"""
import csv
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "data/regime/mon_Q_regime.csv"
R_SCRIPT = ROOT / "data/regime/calc_hydrological_regime.r"
OUT = ROOT / "ShyftBench/Generated/Regime.lean"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rows() -> list[tuple[str, int]]:
    with CSV.open(newline="") as f:
        reader = csv.reader(f, delimiter=" ")
        header = next(reader)
        if header[1] != "st_id" or header[-1] != "regime":
            sys.exit(f"unexpected header in {CSV}: {header}")
        return [(r[1], int(r[-1])) for r in reader]


def render() -> str:
    body = ",\n".join(f'  ("{sid}", {code})' for sid, code in rows())
    return f"""-- GENERATED by scripts/regime_table.py from data/regime/mon_Q_regime.csv. Do not edit.
import ShyftBench.Domain

namespace ShyftBench.Generated

/-- SHA-256 of `data/regime/mon_Q_regime.csv`. -/
def regimeCsvSha256 : String := "{sha256(CSV)}"

/-- SHA-256 of `data/regime/calc_hydrological_regime.r`, the script that produced the CSV. -/
def regimeScriptSha256 : String := "{sha256(R_SCRIPT)}"

/-- Station id and regime code (0 transition, 1 mountain, 2 inland, 3 atlantic, 4 baltic),
in CSV row order. -/
def regimeRows : List (String × Nat) := [
{body}
]

end ShyftBench.Generated
"""


def main() -> None:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run scripts/regime_table.py")
        print("regime table up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
